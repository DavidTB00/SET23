-- H2 schema for ostfold_husflidslag, adapted from MySQL export 2026-11-05.
-- Safe to run on application startup: existing tables are preserved.

CREATE TABLE IF NOT EXISTS rolle (
                                     rolle_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     rolle_navn VARCHAR(45) NOT NULL UNIQUE
    );

CREATE TABLE IF NOT EXISTS bruker (
                                      bruker_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      etternavn VARCHAR(45) NOT NULL,
    fornavn VARCHAR(45) NOT NULL,
    epost VARCHAR(255) NOT NULL UNIQUE,
    passord_hash VARCHAR(255) NOT NULL,
    rolle_id INT NOT NULL,
    CONSTRAINT fk_bruker_rolle FOREIGN KEY (rolle_id) REFERENCES rolle(rolle_id)
    );

CREATE TABLE IF NOT EXISTS bilde (
                                     bilde_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     filsti VARCHAR(500) NOT NULL,
    alternativtekst VARCHAR(255) NOT NULL
    );

CREATE TABLE IF NOT EXISTS kurs (
                                    kurs_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    kurs_navn VARCHAR(100) NOT NULL,
    beskrivelse CLOB NOT NULL
    );

CREATE TABLE IF NOT EXISTS artikkel (
                                        artikkel_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        tittel VARCHAR(150) NOT NULL,
    ingress VARCHAR(500) NOT NULL,
    forfatter_id INT NOT NULL,
    publisert_dato TIMESTAMP DEFAULT NULL,
    artikkelstatus VARCHAR(20) NOT NULL,
    CONSTRAINT chk_artikkelstatus CHECK (artikkelstatus IN ('UTKAST', 'PUBLISERT', 'ARKIVERT')),
    CONSTRAINT fk_artikkel_bruker FOREIGN KEY (forfatter_id) REFERENCES bruker(bruker_id)
    );

CREATE TABLE IF NOT EXISTS innholdsblokk (
                                             blokk_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             artikkel_id INT NOT NULL,
                                             blokktype VARCHAR(10) NOT NULL,
    tekst CLOB,
    bilde_id INT DEFAULT NULL,
    rekkefolge INT NOT NULL,
    bildestorrelse VARCHAR(20) DEFAULT NULL,
    CONSTRAINT chk_blokktype CHECK (blokktype IN ('TEKST', 'BILDE')),
    CONSTRAINT chk_bildestorrelse CHECK (bildestorrelse IN ('LITEN', 'MEDIUM', 'STOR', 'FULL_BREDDE')),
    CONSTRAINT uq_innholdsblokk_artikkel_rekkefolge UNIQUE (artikkel_id, rekkefolge),
    CONSTRAINT fk_innholdsblokk_artikkel FOREIGN KEY (artikkel_id) REFERENCES artikkel(artikkel_id),
    CONSTRAINT fk_innholdsblokk_bilde FOREIGN KEY (bilde_id) REFERENCES bilde(bilde_id)
    );

CREATE TABLE IF NOT EXISTS kursgjennomforing (
                                                 gjennomforing_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                 kurs_id INT NOT NULL,
                                                 starttidspunkt TIMESTAMP NOT NULL,
                                                 sluttidspunkt TIMESTAMP NOT NULL,
                                                 ordinar_pris DECIMAL(10,2) NOT NULL,
    medlemspris DECIMAL(10,2) NOT NULL,
    antall_plasser INT NOT NULL,
    sted VARCHAR(150) NOT NULL,
    pameldingsfrist TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT chk_kursgjennomforing_status CHECK (status IN ('PLANLAGT', 'APEN', 'AVLYST')),
    CONSTRAINT fk_kursgjennomforing_kurs FOREIGN KEY (kurs_id) REFERENCES kurs(kurs_id)
    );

CREATE TABLE IF NOT EXISTS medlemskap (
                                          medlemskap_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          bruker_id INT NOT NULL UNIQUE,
                                          startdato DATE NOT NULL,
                                          sluttdato DATE NOT NULL,
                                          CONSTRAINT fk_medlemskap_bruker FOREIGN KEY (bruker_id) REFERENCES bruker(bruker_id)
    );

CREATE TABLE IF NOT EXISTS pamelding (
                                         pamelding_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         bruker_id INT DEFAULT NULL,
                                         gjennomforing_id INT NOT NULL,
                                         pameldingsdato TIMESTAMP NOT NULL,
                                         fornavn VARCHAR(45) NOT NULL,
    etternavn VARCHAR(45) NOT NULL,
    epost VARCHAR(255) NOT NULL,
    pameldingsstatus VARCHAR(20) NOT NULL,
    tilbudsfrist TIMESTAMP DEFAULT NULL,
    CONSTRAINT chk_pameldingsstatus CHECK (pameldingsstatus IN ('PAMELDT', 'VENTELISTE', 'TILBUDT', 'AVMELDT')),
    CONSTRAINT uq_pamelding_epost_gjennomforing UNIQUE (epost, gjennomforing_id),
    CONSTRAINT fk_pamelding_bruker FOREIGN KEY (bruker_id) REFERENCES bruker(bruker_id),
    CONSTRAINT fk_pamelding_kursgjennomforing FOREIGN KEY (gjennomforing_id) REFERENCES kursgjennomforing(gjennomforing_id)
    );
